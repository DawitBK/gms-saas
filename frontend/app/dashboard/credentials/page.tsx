'use client';

import Image from 'next/image';
import Link from 'next/link';
import { useEffect, useMemo, useState } from 'react';
import { useSearchParams } from 'next/navigation';
import dynamic from 'next/dynamic';
import { AlertTriangle, BadgeCheck, Clock3, KeyRound, Loader2, QrCode, ShieldCheck } from 'lucide-react';

// Only rendered inside an expanded credential row, not on first paint —
// loading it eagerly pulled the whole qrcode.react library into every
// credentials-list page load regardless of whether any row is expanded.
// qrcode.react 4 removed the default export this used to resolve to. That
// default was a thin wrapper that picked a renderer from a `renderAs` prop and
// fell back to canvas — and no call site here passes `renderAs`, so naming
// QRCodeCanvas explicitly renders exactly what it rendered before.
const QRCode = dynamic(() => import('qrcode.react').then((m) => m.QRCodeCanvas), { ssr: false });
import PaginationControls from '@shared/components/PaginationControls';
import { useVisitsList } from '@features/visits/hooks';
import { useVisitCredentials } from '@features/credentials/hooks';
import { resolveVisitScanUrl } from '@shared/lib/qr-links';
import { apiClient } from '@shared/lib/api-client';
import { formatDateTime } from '@shared/lib/datetime';
import { useResetOnChange } from '@shared/hooks/useResetOnChange';

export default function CredentialCenterPage() {
  const searchParams = useSearchParams();
  const [page, setPage] = useState(1);
  const limit = 5;
  const visitsQuery = useVisitsList({ page, limit });
  const visits = useMemo(() => visitsQuery.data?.data ?? [], [visitsQuery.data]);
  const requestedVisitId = useMemo(() => {
    const rawVisitId = searchParams.get('visit');
    if (!rawVisitId) {
      return null;
    }

    const parsed = Number(rawVisitId);
    return Number.isFinite(parsed) && parsed > 0 ? parsed : null;
  }, [searchParams]);
  const hasNextPage = page < (visitsQuery.data?.meta?.totalPages ?? 1);
  const defaultVisitId = useMemo(
    () =>
      (requestedVisitId &&
      visits.some((visit) => visit.id === requestedVisitId)
        ? requestedVisitId
        : undefined) ??
      visits.find((visit) => visit.latest_credential)?.id ??
      visits[0]?.id ??
      null,
    [requestedVisitId, visits]
  );
  const [selectedVisitId, setSelectedVisitId] = useState<number | null>(null);

  useResetOnChange([requestedVisitId, visits], () => {
    if (
      requestedVisitId &&
      visits.some((visit) => visit.id === requestedVisitId)
    ) {
      setSelectedVisitId(requestedVisitId);
    }
  });

  const activeVisitId = selectedVisitId ?? defaultVisitId;
  const credentialsQuery = useVisitCredentials(activeVisitId);
  const credentials = credentialsQuery.data ?? [];
  const activeCredential = credentials.find((credential) => credential.status === 'ACTIVE') ?? credentials[0] ?? null;
  const selectedVisit = visits.find((visit) => visit.id === activeVisitId) ?? null;
  const qrCodeValue = String(activeCredential?.metadata?.qr_code ?? selectedVisit?.qr_code ?? activeCredential?.id ?? '');
  const fallbackMessage =
    activeCredential?.fallback_issued
      ? activeCredential.fallback_message ?? 'UniFi was unreachable, so the system issued an internal QR and PIN for this visit.'
      : null;
  const qrImageSrc = typeof activeCredential?.metadata?.unifi_qr_image_data_uri === 'string'
    ? activeCredential.metadata.unifi_qr_image_data_uri
    : '';
  // Derived, not state. resolveVisitScanUrl is a pure function of these two
  // values, so mirroring its result into state through an effect only added a
  // render — and rendered the QR panel once with an empty URL first.
  const qrScanUrl = resolveVisitScanUrl(qrCodeValue, activeCredential?.metadata?.qr_url);
  const [isDownloading, setIsDownloading] = useState(false);

  const downloadQr = async () => {
    if (!activeVisitId) return;
    setIsDownloading(true);
    try {
      const container = document.getElementById('qr-container');
      if (!container) throw new Error('QR not found');

      const img = container.querySelector('img');
      const svg = container.querySelector('svg');

      let downloadUrl = '';

      if (img && img.src) {
        // If it's an image (e.g. from UniFi data URI)
        if (img.src.startsWith('data:')) {
          downloadUrl = img.src;
        } else {
          // Fallback to fetch if it's a real URL (shouldn't happen for data URIs)
          const response = await fetch(img.src);
          const blob = await response.blob();
          downloadUrl = window.URL.createObjectURL(blob);
        }
      } else if (svg) {
        // If it's an SVG generated by QRCode
        const svgData = new XMLSerializer().serializeToString(svg);
        const canvas = document.createElement('canvas');
        const ctx = canvas.getContext('2d');
        const imgObj = new window.Image();
        
        await new Promise((resolve, reject) => {
          imgObj.onload = resolve;
          imgObj.onerror = reject;
          imgObj.src = 'data:image/svg+xml;base64,' + btoa(unescape(encodeURIComponent(svgData)));
        });

        const padding = 1;
        canvas.width = imgObj.width + (padding * 2);
        canvas.height = imgObj.height + (padding * 2);
        // Fill white background including padding
        if (ctx) {
          ctx.fillStyle = '#ffffff';
          ctx.fillRect(0, 0, canvas.width, canvas.height);
          ctx.drawImage(imgObj, padding, padding);
        }
        downloadUrl = canvas.toDataURL('image/png');
      }

      if (!downloadUrl) throw new Error('Could not extract QR');

      const a = document.createElement('a');
      a.href = downloadUrl;
      a.download = `visit-${activeVisitId}-qr.png`;
      document.body.appendChild(a);
      a.click();
      a.remove();
      
      if (downloadUrl.startsWith('blob:')) {
        window.URL.revokeObjectURL(downloadUrl);
      }
    } catch (err) {
      console.error('Failed to download QR:', err);
      // Fallback to API if DOM extraction fails
      const response = await apiClient.get(`/visits/${activeVisitId}/qr.png`, { responseType: 'blob' });
      const blob = new Blob([response.data], { type: 'image/png' });
      const url = window.URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `visit-${activeVisitId}-qr.png`;
      document.body.appendChild(a);
      a.click();
      a.remove();
      window.URL.revokeObjectURL(url);
    } finally {
      setIsDownloading(false);
    }
  };

  return (
    <div className="space-y-8">
      <section className="ui-hero">
        <p className="text-xs uppercase tracking-[0.35em] text-slate-500">Credential center</p>
        <h1 className="mt-3 text-3xl font-semibold tracking-tight text-white sm:text-4xl">
          Your active access pass, ready before arrival.
        </h1>
        <p className="mt-3 max-w-2xl text-sm leading-6 text-slate-400 sm:text-base">
          Use this page to retrieve your issued QR credential, verify the access window, and keep your backup PIN available for reception.
        </p>
      </section>

      <section className="grid gap-6 xl:grid-cols-[0.9fr_1.1fr] items-start">
        <div className="ui-card ui-card-elevated h-fit">
          <div className="flex items-center justify-between gap-4">
            <div>
              <h2 className="text-xl font-semibold text-white">Select visit</h2>
              <p className="mt-2 text-sm text-slate-400">Choose the visit you want to present at check-in.</p>
            </div>
            <ShieldCheck className="h-5 w-5 text-cyan-400" />
          </div>

          {visitsQuery.isLoading ? (
            <div className="mt-6 space-y-3">
              {Array.from({ length: 4 }).map((_, index) => (
                <div key={index} className="h-20 animate-pulse rounded-2xl bg-slate-800/70" />
              ))}
            </div>
          ) : visitsQuery.isError ? (
            <div className="mt-6 rounded-2xl border border-rose-500/30 bg-rose-500/10 p-4 text-sm text-rose-200">
              We couldn&apos;t load your visits right now.
            </div>
          ) : visits.length === 0 ? (
            <div className="mt-6 rounded-2xl border border-dashed border-slate-800 bg-slate-950/60 p-5 text-sm text-slate-400">
              No visits yet. Book a visit first and your access pass will appear here after approval.
            </div>
          ) : (
            <div className="mt-6 space-y-3 max-h-[500px] overflow-y-auto ui-scrollbar pr-2">
              {visits.map((visit) => {
                const isSelected = visit.id === activeVisitId;
                return (
                  <button
                    key={visit.id}
                    type="button"
                    onClick={() => setSelectedVisitId(visit.id)}
                    className={`w-full rounded-2xl border p-4 text-left transition ${
                      isSelected
                        ? 'border-cyan-500/40 bg-cyan-500/10 shadow-sm'
                        : 'border-slate-800 bg-slate-950/60 hover:border-slate-700 hover:bg-slate-950/70'
                    }`}
                    aria-pressed={isSelected}
                    aria-label={`Select visit ${visit.reference_number || visit.id}`}
                  >
                    <div className="flex items-start justify-between gap-4">
                      <div>
                        <p className="font-medium text-white">{visit.reference_number || `Visit #${visit.id}`}</p>
                        <p className="mt-1 text-sm text-slate-400">{formatDateTime(visit.scheduled_start)}</p>
                      </div>
                      <span className="rounded-full border border-slate-700 px-3 py-1 text-[11px] uppercase tracking-[0.22em] text-slate-300">
                        {visit.latest_credential?.status ?? visit.status}
                      </span>
                    </div>
                    <p className="mt-3 text-sm text-slate-400">
                      Approval: {visit.latest_approval?.status ?? 'Awaiting review'}
                    </p>
                    <p className="mt-1 text-sm text-slate-500">
                      Assigned host: {visit.host?.name ?? 'Host not assigned yet'}
                    </p>
                  </button>
                );
              })}
            </div>
          )}
        </div>

        <div className="ui-card ui-card-elevated">
          <div className="flex items-center justify-between gap-4">
            <div>
              <h2 className="text-xl font-semibold text-white">Issued credential</h2>
              <p className="mt-2 text-sm text-slate-400">Present the QR code at arrival or give reception the backup PIN.</p>
            </div>
            <QrCode className="h-5 w-5 text-cyan-400" />
          </div>

          {!activeVisitId ? (
            <div className="mt-6 rounded-2xl border border-dashed border-slate-800 bg-slate-950/60 p-5 text-sm text-slate-400">
              Select a visit to load its credential details.
            </div>
          ) : credentialsQuery.isLoading ? (
            <div className="mt-6 flex h-[28rem] items-center justify-center rounded-3xl bg-slate-950/60">
              <Loader2 className="h-6 w-6 animate-spin text-cyan-400" />
            </div>
          ) : credentialsQuery.isError ? (
            <div className="mt-6 rounded-2xl border border-rose-500/30 bg-rose-500/10 p-4 text-sm text-rose-200">
              We couldn&apos;t load the credential for this visit.
            </div>
          ) : activeCredential ? (
            <div className="mt-6 space-y-5">
              <div className="grid gap-5 lg:grid-cols-[1fr_0.9fr] items-start">
                <div className="rounded-3xl border border-slate-800 bg-slate-950/70 p-5 shadow-sm">
                  <div className="flex items-center gap-2 text-sm text-emerald-300">
                    <BadgeCheck className="h-4 w-4" />
                    {activeCredential.status}
                  </div>
                  {fallbackMessage ? (
                    <div className="mt-4 rounded-2xl border border-amber-500/30 bg-amber-500/10 p-4 text-sm text-amber-100">
                      <p className="font-medium text-amber-50">System credential issued</p>
                      <p className="mt-1 text-amber-100/90">{fallbackMessage}</p>
                    </div>
                  ) : null}
                  <div id="qr-container" className="mt-6 inline-flex rounded-[2rem] bg-white p-5">
                    {qrImageSrc ? (
                      <Image
                        src={qrImageSrc}
                        alt="Visit QR code"
                        width={220}
                        height={220}
                        unoptimized
                        className="rounded-xl"
                      />
                    ) : (
                      <QRCode value={qrScanUrl || qrCodeValue} size={220} />
                    )}
                  </div>
                  <button
                    type="button"
                    onClick={downloadQr}
                    disabled={isDownloading || !activeVisitId}
                    className="ui-btn ui-btn-secondary mt-4 text-xs font-semibold hover:border-cyan-500/40 hover:text-cyan-200"
                  >
                    {isDownloading ? <Loader2 className="h-4 w-4 animate-spin" /> : <QrCode className="h-4 w-4" />}
                    Download QR (PNG)
                  </button>
                  {qrScanUrl && !qrScanUrl.startsWith('data:') ? (
                    <div className="mt-4 rounded-2xl border border-slate-800 bg-slate-900/80 p-4 text-sm text-slate-300">
                      <p className="text-xs uppercase tracking-[0.22em] text-slate-500">Raw QR token</p>
                      <p className="mt-2 block break-all font-medium text-cyan-300">
                        {qrScanUrl}
                      </p>
                    </div>
                  ) : null}
                  <p className="mt-4 text-sm text-slate-400">
                    Credential provider: <span className="font-medium text-slate-200">{activeCredential.provider}</span>
                  </p>
                  {activeCredential.fallback_issued ? (
                    <p className="mt-1 text-sm text-amber-300">
                      Fallback mode: system credential active because UniFi could not be reached.
                    </p>
                  ) : null}
                  <p className="mt-1 text-sm text-slate-500">
                    QR source: <span className="font-medium text-slate-300">{activeCredential.metadata?.qr_delivery_source ?? 'system'}</span>
                  </p>
                </div>

                <div className="space-y-4">
                  <InfoCard
                    icon={Clock3}
                    label="Access window"
                    value={`${formatDateTime(activeCredential.valid_from)} to ${formatDateTime(activeCredential.valid_until)}`}
                  />
                  <InfoCard
                    icon={KeyRound}
                    label="Backup PIN"
                    value={String(activeCredential.metadata?.pin_code ?? 'Not available')}
                  />
                  <InfoCard
                    icon={ShieldCheck}
                    label="Assigned doors"
                    value={activeCredential.door_ids.length ? activeCredential.door_ids.join(', ') : 'Access group assigned automatically'}
                  />
                  <InfoCard
                    icon={ShieldCheck}
                    label="Assigned host"
                    value={selectedVisit?.host?.name ?? 'Host not assigned yet'}
                  />
                </div>
              </div>

              <div className="rounded-2xl border border-slate-800 bg-slate-950/60 p-4 text-sm text-slate-300">
                {selectedVisit?.status === 'APPROVED' || selectedVisit?.status === 'CHECKED_IN'
                  ? 'Your visit is approved. Keep this page ready when you arrive at reception or the assigned door.'
                  : 'Your visit is not currently in an active arrival state. Reception may ask you to wait for a fresh approval.'}
              </div>
            </div>
          ) : (
            <div className="mt-6 rounded-2xl border border-amber-500/30 bg-amber-500/10 p-5 text-sm text-amber-100">
              No credential has been issued for this visit yet. Once approval completes, your QR and backup PIN will appear here.
            </div>
          )}
        </div>
      <div className="mt-4">
        <PaginationControls
          page={page}
          onPageChange={setPage}
          hasPrevious={page > 1}
          totalPages={visitsQuery.data?.meta?.totalPages}
          hasNext={hasNextPage}
        />
      </div>

      </section>

      {selectedVisit ? (
        <section className="ui-card ui-card-elevated">
          <div className="flex items-center gap-3 text-sm text-slate-300">
            <AlertTriangle className="h-4 w-4 text-amber-300" />
            Arrival note
          </div>
          <p className="mt-3 text-sm leading-6 text-slate-400">
            {selectedVisit.reference_number || `Visit #${selectedVisit.id}`} is scheduled for {formatDateTime(selectedVisit.scheduled_start)}. If the QR does not scan, provide the backup PIN and a valid ID to reception for manual verification.
          </p>
        </section>
      ) : null}
    </div>
  );
}

function InfoCard({
  icon: Icon,
  label,
  value,
}: {
  icon: React.ComponentType<{ className?: string }>;
  label: string;
  value: string;
}) {
  return (
    <div className="rounded-2xl border border-slate-800 bg-slate-950/70 p-4 shadow-sm">
      <p className="inline-flex items-center gap-2 text-xs uppercase tracking-[0.22em] text-slate-500">
        <Icon className="h-4 w-4" />
        {label}
      </p>
      <p className="mt-2 font-medium text-white">{value}</p>
    </div>
  );
}
